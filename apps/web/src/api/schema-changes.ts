/**
 * Schema change sets (design 11.1, `POST .../schema/changes`): `diffSchemas` turns two
 * schemas into the commands that lead from one to the other, `applySchemaChanges` runs
 * commands on a schema. Elements are matched by stable id, so a rename is an update.
 */
import type { SchemaBody } from './schema-rules';
import type { Attribute, ElementId, SchemaChange, SchemaCommand, SchemaElementType } from './types';

export class SchemaChangeError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SchemaChangeError';
  }
}

type Collection = 'kinds' | 'relations' | 'traits' | 'operations' | 'derivations' | 'sources';
type TopLevelType = Exclude<SchemaElementType, 'attribute'>;

const COLLECTION_OF: Record<TopLevelType, Collection> = {
  kind: 'kinds',
  relation: 'relations',
  trait: 'traits',
  operation: 'operations',
  derivation: 'derivations',
  source: 'sources',
};

const TOP_LEVEL: TopLevelType[] = [
  'kind',
  'relation',
  'trait',
  'operation',
  'derivation',
  'source',
];

/** Elements that own an `attributes` map, diffed entry by entry. */
const ATTRIBUTE_OWNERS: Collection[] = ['kinds', 'relations'];

interface Identified {
  id: ElementId;
  builtin?: boolean;
}

type Document = Record<string, unknown>;

const asDocument = (element: unknown): Document => element as Document;

const same = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b);

function changedFields(before: Document, after: Document, skip: string[]): Document {
  const set: Document = {};
  for (const key of new Set([...Object.keys(before), ...Object.keys(after)])) {
    if (skip.includes(key)) continue;
    if (!same(before[key], after[key])) set[key] = structuredClone(after[key]);
  }
  return set;
}

const command = (verb: 'add' | 'update' | 'remove', type: SchemaElementType): SchemaCommand =>
  `${verb}_${type}`;

function diffAttributes(
  owner: ElementId,
  before: Record<ElementId, Attribute>,
  after: Record<ElementId, Attribute>,
  out: SchemaChange[],
) {
  for (const [id, attribute] of Object.entries(after)) {
    const old = before[id];
    if (old === undefined) {
      out.push({
        command: 'add_attribute',
        arguments: { owner, element: structuredClone(attribute) },
      });
    } else if (!same(old, attribute)) {
      out.push({
        command: 'update_attribute',
        target: id,
        arguments: {
          owner,
          set: changedFields(asDocument(old), asDocument(attribute), []),
        },
      });
    }
  }
  for (const id of Object.keys(before)) {
    if (after[id] === undefined) {
      out.push({ command: 'remove_attribute', target: id, arguments: { owner } });
    }
  }
}

/** Commands that turn `before` into `after`. Built-in Operations are generated by Keeper and skipped. */
export function diffSchemas(before: SchemaBody, after: SchemaBody): SchemaChange[] {
  const removals: SchemaChange[] = [];
  const additions: SchemaChange[] = [];
  const updates: SchemaChange[] = [];

  for (const type of TOP_LEVEL) {
    const collection = COLLECTION_OF[type];
    const old = new Map<ElementId, Identified>(
      (before[collection] as Identified[]).filter((e) => e.builtin !== true).map((e) => [e.id, e]),
    );
    const next = new Map<ElementId, Identified>(
      (after[collection] as Identified[]).filter((e) => e.builtin !== true).map((e) => [e.id, e]),
    );
    const owns = ATTRIBUTE_OWNERS.includes(collection);
    for (const [id, element] of next) {
      const previous = old.get(id);
      if (previous === undefined) {
        additions.push({
          command: command('add', type),
          arguments: { element: structuredClone(element) },
        });
        continue;
      }
      const set = changedFields(
        asDocument(previous),
        asDocument(element),
        owns ? ['attributes'] : [],
      );
      if (Object.keys(set).length > 0) {
        updates.push({ command: command('update', type), target: id, arguments: { set } });
      }
      if (owns) {
        diffAttributes(
          id,
          asDocument(previous)['attributes'] as Record<ElementId, Attribute>,
          asDocument(element)['attributes'] as Record<ElementId, Attribute>,
          updates,
        );
      }
    }
    for (const id of old.keys()) {
      if (!next.has(id))
        removals.push({ command: command('remove', type), target: id, arguments: {} });
    }
  }
  return [...removals, ...additions, ...updates];
}

function listOf(schema: SchemaBody, type: TopLevelType): Identified[] {
  return schema[COLLECTION_OF[type]];
}

function attributeOwner(schema: SchemaBody, id: ElementId | undefined) {
  for (const collection of ATTRIBUTE_OWNERS) {
    const found = (schema[collection] as Identified[]).find((e) => e.id === id);
    if (found !== undefined) return asDocument(found);
  }
  throw new SchemaChangeError(`Attribute owner ${String(id)} does not exist.`);
}

function ownerOf(schema: SchemaBody, change: SchemaChange) {
  const owner = change.arguments['owner'];
  return attributeOwner(schema, typeof owner === 'string' ? owner : undefined);
}

function elementOf(change: SchemaChange): Document {
  const element = change.arguments['element'];
  if (typeof element !== 'object' || element === null) {
    throw new SchemaChangeError(`${change.command} needs an element.`);
  }
  return structuredClone(element) as Document;
}

function applyOne(schema: SchemaBody, change: SchemaChange) {
  const [verb, type] = change.command.split('_') as [
    'add' | 'update' | 'remove',
    SchemaElementType,
  ];
  if (type === 'attribute') {
    const owner = ownerOf(schema, change);
    const attributes = owner['attributes'] as Record<ElementId, Document>;
    if (verb === 'add') {
      const element = elementOf(change);
      attributes[element['id'] as ElementId] = element;
      return;
    }
    const existing = attributes[change.target ?? ''];
    if (existing === undefined)
      throw new SchemaChangeError(`Attribute ${String(change.target)} does not exist.`);
    if (verb === 'remove') {
      delete attributes[change.target ?? ''];
    } else {
      Object.assign(existing, structuredClone(change.arguments['set'] ?? {}));
    }
    return;
  }
  const list = listOf(schema, type);
  if (verb === 'add') {
    const element = elementOf(change);
    if (list.some((e) => e.id === element['id'])) {
      throw new SchemaChangeError(`${type} ${String(element['id'])} exists already.`);
    }
    list.push(element as unknown as Identified);
    return;
  }
  const index = list.findIndex((e) => e.id === change.target);
  if (index < 0) throw new SchemaChangeError(`${type} ${String(change.target)} does not exist.`);
  if (verb === 'remove') {
    list.splice(index, 1);
  } else {
    Object.assign(
      list[index] as unknown as Document,
      structuredClone(change.arguments['set'] ?? {}),
    );
  }
}

/** A copy of `schema` with `changes` applied in order. Throws `SchemaChangeError` on a bad command. */
export function applySchemaChanges(schema: SchemaBody, changes: SchemaChange[]): SchemaBody {
  const next = structuredClone(schema);
  for (const change of changes) applyOne(next, change);
  return next;
}
