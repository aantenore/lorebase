"""Markdown reference of the `lorebase` command line, generated from its Typer application.

The text comes from `typer lorebase_cli.main utils docs`, so the reference cannot drift from the
help of the commands. The run happens in a subprocess with the `LOREBASE_*` variables removed,
because a variable of the shell must not change what the commands document.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "docs" / "reference" / "cli.md"
APP = "lorebase_cli.main"
PROGRAM = "lorebase"
ENV_PREFIX = "LOREBASE_"

FRONT_MATTER = """---
title: Command line reference
description: >-
  Every command and option of the lorebase command line, generated from the Typer application.
---

<!-- Generated by scripts/docs/cli_reference.py (make docs); do not edit. -->

"""
INTRO = """Install the CLI with `uv sync --all-packages` and run `uv run lorebase`; the
[quickstart](../quickstart.md) shows it at work, and `lorebase COMMAND --help` prints the text below
for one command. The server it talks to is described in the [REST API reference](api.md).

"""


def render() -> str:
    """The reference page as text."""
    env = {k: v for k, v in os.environ.items() if not k.startswith(ENV_PREFIX)}
    env["NO_COLOR"] = "1"
    command = [sys.executable, "-m", "typer", APP, "utils", "docs", "--name", PROGRAM]
    result = subprocess.run(command, capture_output=True, text=True, env=env, check=True)
    body = result.stdout.strip()
    heading, _, rest = body.partition("\n")
    if heading != f"# `{PROGRAM}`":
        raise RuntimeError(f"unexpected first line from typer: {heading!r}")
    return f"{FRONT_MATTER}# Command line reference\n\n{INTRO}## `{PROGRAM}`\n{_demote(rest)}\n"


def _demote(text: str) -> str:
    """Push every heading of the Typer output one level down, below the page title."""
    lines = []
    fenced = False
    for line in text.split("\n"):
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and line.startswith("#"):
            line = "#" + line
        lines.append(line)
    return "\n".join(lines)
